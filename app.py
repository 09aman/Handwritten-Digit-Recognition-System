with st.sidebar:
    st.header("Model settings")
    selected_model = st.selectbox(
        "Choose a trained model",
        list(MODEL_OPTIONS.keys()),
        index=0,
    )
    model_filename = MODEL_OPTIONS[selected_model]
    model_path = MODEL_DIR / model_filename

    st.caption("Model file")
    st.code(f"models/{model_filename}", language="text")
    st.divider()
    st.markdown("**Input format**")
    st.write("28 × 28 grayscale image")
    st.write("Pixel range: 0–255")
    st.caption("The input is prepared to match the preprocessing in your MNIST notebook.")

