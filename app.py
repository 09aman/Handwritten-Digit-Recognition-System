@st.cache_resource
def load_model(model_path: str):
    """Load a saved Keras model once and reuse it across Streamlit reruns."""
    return tf.keras.models.load_model(model_path)


def preprocess_image(image: Image.Image) -> np.ndarray:
    """
    Convert an input image to the 28x28 grayscale format used by the notebook.

    The notebook trains on MNIST CSV pixel values in the 0..255 range
    (it does not divide them by 255), so this function also returns 0..255.
    """
    image = ImageOps.grayscale(image)
    arr = np.asarray(image, dtype=np.uint8)

    # MNIST uses a dark background and a bright digit.
    # Invert typical white-background uploads.
    if float(arr.mean()) > 127:
        arr = 255 - arr

    # Remove faint background noise and find the digit bounding box.
    mask = arr > 30
    if not mask.any():
        raise ValueError("No digit was detected. Draw or upload a clearer digit.")

    ys, xs = np.where(mask)
    cropped = arr[ys.min():ys.max() + 1, xs.min():xs.max() + 1]

    # Fit the digit inside a 20x20 area, preserving its aspect ratio.
    digit = Image.fromarray(cropped)
    digit.thumbnail((20, 20), Image.Resampling.LANCZOS)

    canvas = Image.new("L", (28, 28), color=0)
    x = (28 - digit.width) // 2
    y = (28 - digit.height) // 2
    canvas.paste(digit, (x, y))

    return np.asarray(canvas, dtype=np.float32)


def predict_digit(model, model_name: str, image_28: np.ndarray) -> np.ndarray:
    """Prepare the input shape expected by each model and return 10 probabilities."""
    if model_name == "CNN":
        model_input = image_28.reshape(1, 28, 28, 1)
    else:
        model_input = image_28.reshape(1, 28, 28)

    probabilities = model.predict(model_input, verbose=0)[0]
    return np.asarray(probabilities)


